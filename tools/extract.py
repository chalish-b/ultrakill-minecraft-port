"""Rebuilds everything extracted or generated from the local ULTRAKILL install and the mod's Minecraft dependency.

    uv run tools/extract.py

  reference/decomp/     ULTRAKILL's game code (Assembly-CSharp), decompiled with ILSpy
  reference/player/     the player prefab and physics settings, as JSON
  reference/minecraft/  Minecraft 26.3 sources, as generated by Loom
  mod/src/generated/    ULTRAKILL's sounds, first-person models with their animations, and icons, packaged into the mod

Needs: dotnet + ilspycmd (dotnet tool install -g ilspycmd), uv, JDK 25.
"""
import os
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from ultrakill_paths import MANAGED, REPO  # noqa: E402

# Homebrew's dotnet and openjdk@25 aren't found on their own.
HOMEBREW_DOTNET = Path("/opt/homebrew/opt/dotnet/libexec")
HOMEBREW_JDK = Path("/opt/homebrew/opt/openjdk@25/libexec/openjdk.jdk/Contents/Home")


def run(*command, cwd=None):
    result = subprocess.run([str(part) for part in command], cwd=cwd)
    if result.returncode != 0:
        sys.exit(result.returncode)


def find_tool(name, hint):
    tool = shutil.which(name, path=os.pathsep.join([os.environ.get("PATH", ""), str(Path.home() / ".dotnet" / "tools")]))
    if tool is None:
        sys.exit(f"{name} not found. {hint}")
    return tool


def main():
    if sys.platform == "darwin":
        if "DOTNET_ROOT" not in os.environ and HOMEBREW_DOTNET.is_dir():
            os.environ["DOTNET_ROOT"] = str(HOMEBREW_DOTNET)
        if "JAVA_HOME" not in os.environ and HOMEBREW_JDK.is_dir():
            os.environ["JAVA_HOME"] = str(HOMEBREW_JDK)

    ilspycmd = find_tool("ilspycmd", "Install it with: dotnet tool install -g ilspycmd")
    uv = find_tool("uv", "Install it from https://docs.astral.sh/uv/")
    tools = REPO / "tools"
    mod = REPO / "mod"
    reference = REPO / "reference"
    reference.mkdir(exist_ok=True)

    print("Decompiling Assembly-CSharp...", flush=True)
    run(ilspycmd, "-p", "-o", reference / "decomp", MANAGED / "Assembly-CSharp.dll")

    print("Dumping the player prefab...", flush=True)
    run(uv, "run", "--quiet", tools / "dump_player.py")

    print("Extracting sounds...", flush=True)
    run(uv, "run", "--quiet", tools / "extract_sounds.py")

    print("Extracting models...", flush=True)
    run(uv, "run", "--quiet", tools / "extract_models.py")

    print("Generating Minecraft sources...", flush=True)
    gradlew = mod / ("gradlew.bat" if sys.platform == "win32" else "gradlew")
    run(gradlew, "genSources", "--console=plain", "-q", cwd=mod)
    sources = reference / "minecraft"
    sources.mkdir(exist_ok=True)
    for jar in (mod / ".gradle" / "loom-cache" / "minecraftMaven" / "net" / "minecraft").glob("minecraft-*/*/*-sources.jar"):
        with zipfile.ZipFile(jar) as archive:
            archive.extractall(sources)

    print("Done.")


if __name__ == "__main__":
    main()
